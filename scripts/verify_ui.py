import json
import os
import sys
from pathlib import Path
from urllib.parse import urlparse
from playwright.sync_api import sync_playwright, expect
from qa_helpers import qa_api, api_matches

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[1]
BASE = os.environ.get("TRILINGO_UI_URL", "http://127.0.0.1:5173")
OUT = ROOT / "artifacts" / "screenshots"
OUT.mkdir(parents=True, exist_ok=True)
report = []
QA_API = qa_api()
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context()
    external = []
    def local_only(route):
        if urlparse(route.request.url).hostname in {"127.0.0.1", "localhost"} and api_matches(route.request.url, QA_API):
            route.continue_()
        else:
            external.append(route.request.url)
            route.abort()
    context.route("**/*", local_only)
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    held = []
    page.set_viewport_size({"width": 390, "height": 900})
    page.route("**/api/v1/health", lambda route: held.append(route))
    page.goto(BASE, wait_until="domcontentloaded")
    expect(page.get_by_role("status", name="Loading your workspace")).to_be_visible()
    page.screenshot(path=str(OUT / "loading-390.png"), full_page=True)
    page.wait_for_timeout(50)
    for route in held:
        route.continue_()
    page.unroute("**/api/v1/health")
    page.wait_for_load_state("networkidle")
    page.route("**/api/v1/health", lambda route: route.abort())
    page.reload()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("alert")).to_contain_text("Start the backend")
    page.screenshot(path=str(OUT / "connection-error-390.png"), full_page=True)
    page.unroute("**/api/v1/health")
    page.get_by_role("button", name="Retry connection").click()
    expect(page.get_by_role("heading", name="Start with a small hello")).to_be_visible()
    page.route("**/api/v1/courses", lambda route: route.fulfill(status=200, content_type="application/json", body="[]"))
    page.reload()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("heading", name="No course imported yet")).to_be_visible()
    page.unroute("**/api/v1/courses")
    page.get_by_role("button", name="Refresh courses").click()
    expect(page.locator(".lesson-node")).to_have_count(6)
    report.append("Real loading, connection-failure/retry, and empty-course/recovery states")
    expect(page.get_by_role("heading", name="Start with a small hello")).to_be_visible()
    for route in ["learn", "practice", "library", "profile", "preview"]:
        page.goto(BASE + "/#" + route)
        page.wait_for_load_state("networkidle")
        for width in [320, 390, 768, 1440]:
            page.set_viewport_size({"width": width, "height": 900})
            assert not page.evaluate("document.documentElement.scrollWidth > innerWidth"), (route, width)
            page.screenshot(path=str(OUT / f"{route}-{width}.png"), full_page=True)
        report.append(f"{route}: responsive 320/390/768/1440, no horizontal overflow")
    page.set_viewport_size({"width": 390, "height": 900})
    page.goto(BASE + "/#library")
    page.get_by_role("link", name="Skip to content").focus()
    page.keyboard.press("Enter")
    assert page.url.endswith("#library")
    expect(page.locator("main")).to_be_focused()
    page.get_by_label("Find a word").fill("zzzzzz")
    expect(page.get_by_role("status")).to_contain_text("No matching words")
    page.get_by_label("Find a word").fill("hello")
    expect(page.locator(".word-entry")).to_have_count(1)
    report.append("Skip link retains destination and focuses main; vocabulary search and empty state")
    page.goto(BASE + "/#learn")
    later = page.get_by_role("button", name="Notice sound differences. Available. Browse lesson")
    later.click()
    expect(page.get_by_role("dialog")).to_be_visible()
    expect(page.get_by_role("button", name="Start lesson · Upcoming")).to_be_disabled()
    for _ in range(10):
        page.keyboard.press("Tab")
        assert page.evaluate("document.activeElement.closest('dialog') !== null")
    page.keyboard.press("Escape")
    expect(later).to_be_focused()
    report.append("Later lesson opens without enrollment; native dialog traps and restores keyboard focus")
    page.goto(BASE + "/#profile")
    name = page.get_by_label("Your name", exact=True)
    name.fill("QA learner")
    zone = page.get_by_label("Timezone", exact=False)
    zone.fill("Not/AZone")
    page.get_by_role("button", name="Save preferences").click()
    expect(page.get_by_role("alert")).to_contain_text("timezone")
    expect(name).to_have_value("QA learner")
    zone.fill("Asia/Singapore")
    page.get_by_label("Suggested XP goal").fill("37")
    page.route("**/api/v1/settings", lambda route: route.abort() if route.request.method == "PATCH" else route.continue_())
    page.get_by_role("button", name="Save preferences").click()
    expect(page.get_by_role("alert")).to_contain_text("Start the backend")
    expect(page.get_by_label("Suggested XP goal")).to_have_value("37")
    page.unroute("**/api/v1/settings")
    page.get_by_label("Reduce interface motion").check()
    page.get_by_role("button", name="Save preferences").click()
    expect(page.get_by_role("status").filter(has_text="Profile and preferences saved")).to_be_visible()
    page.reload()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_label("Your name", exact=True)).to_have_value("QA learner")
    expect(page.get_by_label("Suggested XP goal")).to_have_value("37")
    assert page.locator("html").get_attribute("data-motion") == "reduced"
    report.append("Invalid timezone details, network failure input preservation, retry, reload persistence, reduced motion")
    page.goto(BASE + "/#preview")
    answer = page.get_by_label("Fixture answer")
    answer.fill("こんにちは")
    answer.dispatch_event("keydown", {"key": "Enter", "isComposing": True})
    expect(page.get_by_role("button", name="Check preview")).to_be_enabled()
    page.get_by_role("button", name="Check preview").click()
    expect(page.get_by_role("button", name="Checking…")).to_be_disabled()
    page.get_by_role("button", name="Skip preview").click()
    page.wait_for_timeout(650)
    expect(page.get_by_role("status").filter(has_text="Skipped example")).to_be_visible()
    page.get_by_role("button", name="Continue preview").click()
    expect(page.get_by_label("Example exercise position")).to_have_attribute("value", "2")
    page.get_by_label("Preset feedback").select_option("correct")
    page.get_by_role("button", name="Check preview").click()
    expect(page.get_by_role("status").filter(has_text="Correct example")).to_be_visible()
    page.get_by_label("Preset feedback").select_option("incorrect")
    page.get_by_role("button", name="Check preview").click()
    expect(page.get_by_role("alert").filter(has_text="Incorrect example")).to_be_visible()
    page.get_by_role("button", name="Continue preview").click()
    answer.fill("あきです")
    page.get_by_role("button", name="Exit / pause preview").click()
    page.get_by_role("button", name="Resume preview").click()
    expect(answer).to_have_value("あきです")
    page.get_by_role("button", name="Reveal / hint preview").click()
    expect(page.get_by_role("status").filter(has_text="Assisted example")).to_be_visible()
    page.get_by_role("button", name="Finish preview").click()
    expect(page.get_by_role("status").filter(has_text="Finished preview")).to_be_visible()
    page.get_by_role("button", name="Replay preview").click()
    editor = page.get_by_label("Try Japanese input")
    editor.fill("わたしはアキです。\n日本語を勉強しています。")
    editor.dispatch_event("keydown", {"key": "Enter", "ctrlKey": True, "isComposing": True})
    expect(page.get_by_role("dialog")).to_have_count(0)
    page.get_by_role("button", name="Simulate a save failure").click()
    expect(page.get_by_role("alert").filter(has_text="simulated draft save failed")).to_be_visible()
    expect(editor).to_have_value("わたしはアキです。\n日本語を勉強しています。")
    opener = page.get_by_role("button", name="Open dialog preview")
    opener.click()
    expect(page.get_by_role("dialog")).to_be_visible()
    page.keyboard.press("Escape")
    expect(opener).to_be_focused()
    page.get_by_role("button", name="Start elapsed time").click()
    page.wait_for_timeout(1100)
    page.get_by_role("button", name="Pause elapsed time").click()
    expect(page.get_by_text("0:01 elapsed · No expiry")).to_be_visible()
    page.get_by_label("Show elapsed time fixture").uncheck()
    expect(page.get_by_text("0:01 elapsed · No expiry")).to_have_count(0)
    page.get_by_role("button", name="Recap fixture", exact=True).click()
    expect(page.get_by_role("dialog")).to_be_visible()
    page.keyboard.press("Escape")
    page.get_by_role("button", name="Writing", exact=True).click()
    expect(page.get_by_role("button", name="Writing", exact=True)).to_have_attribute("aria-pressed", "true")
    page.get_by_label("Fixture accent preference").select_option("Plum notes")
    expect(page.locator(".cosmetic-preview")).to_have_attribute("data-accent", "Plum notes")
    report.append("Fixture pending cancellation, mistakes/skip/reveal/continue/finish, pause/resume, composition-event guards, save recovery, timer pause/hide")
    page.set_viewport_size({"width": 320, "height": 900})
    page.add_style_tag(content="html { font-size: 200% !important; }")
    page.screenshot(path=str(OUT / "preview-320-text200.png"), full_page=True)
    assert not page.evaluate("document.documentElement.scrollWidth > innerWidth"), "Text resizing overflow"
    report.append("320px with 200% text: no horizontal overflow")
    fault = context.new_page()
    fault.goto(BASE + "/tests/boundary.html")
    expect(fault.get_by_role("heading", name="The page could not open")).to_be_visible()
    expect(fault.get_by_role("button", name="Reload app")).to_be_visible()
    expect(fault.get_by_text("Intentional boundary QA failure", exact=True)).to_have_count(0)
    fault.close()
    report.append("Actual React error boundary catches a deliberate isolated rendering failure without exposing its details")
    assert not errors, errors
    assert not external, external
    print(json.dumps({"checks": report, "page_errors": errors, "external_requests": external}, ensure_ascii=False, indent=2))
    (ROOT / "artifacts" / "ui-results.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    browser.close()
